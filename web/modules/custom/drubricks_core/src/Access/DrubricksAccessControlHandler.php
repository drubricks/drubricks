<?php

declare(strict_types=1);

namespace Drupal\drubricks_core\Access;

use Drupal\Core\Access\AccessResult;
use Drupal\Core\Access\AccessResultInterface;
use Drupal\Core\Cache\CacheableMetadata;
use Drupal\Core\Cache\RefinableCacheableDependencyInterface;
use Drupal\Core\Entity\EntityAccessControlHandler;
use Drupal\Core\Entity\EntityHandlerInterface;
use Drupal\Core\Entity\EntityInterface;
use Drupal\Core\Entity\EntityTypeInterface;
use Drupal\Core\Entity\EntityTypeManagerInterface;
use Drupal\Core\Session\AccountInterface;
use Drupal\drubricks_core\Screen\ScreenHandler;
use Drupal\user\EntityOwnerInterface;
use Symfony\Component\DependencyInjection\ContainerInterface;

/**
 * Access by "{operation} own|any {entity type}" permissions.
 *
 * Permissions are generated by \Drupal\drubricks_core\DrubricksPermissions
 * for every entity type that uses this handler:
 * - "create {type}"
 * - "view own {type}", "view any {type}"
 * - "edit own {type}", "edit any {type}"
 * - "delete own {type}", "delete any {type}"
 * The entity type's admin permission grants everything.
 *
 * "delete" is forbidden — for everyone, admins too — while the screen
 * handler's deleteBlockers() gives reasons (e.g. contacts belong to a
 * company): the Delete actions and operations disappear or show the reason,
 * bulk deletes skip the record, APIs refuse it. Like core's
 * LanguageAccessControlHandler for the default language.
 *
 * @phpstan-consistent-constructor
 */
class DrubricksAccessControlHandler extends EntityAccessControlHandler implements EntityHandlerInterface {

  /**
   * The entity type manager (the screen handler's delete blockers).
   */
  protected EntityTypeManagerInterface $entityTypeManager;

  /**
   * {@inheritdoc}
   */
  public static function createInstance(ContainerInterface $container, EntityTypeInterface $entity_type): static {
    $instance = new static($entity_type);
    $instance->entityTypeManager = $container->get('entity_type.manager');
    return $instance;
  }

  /**
   * Maps entity operations to permission verbs.
   */
  public const OPERATIONS = [
    'view' => 'view',
    'view label' => 'view',
    'update' => 'edit',
    'delete' => 'delete',
  ];

  /**
   * {@inheritdoc}
   */
  protected function checkAccess(EntityInterface $entity, $operation, AccountInterface $account): AccessResultInterface {
    $result = $this->permissionAccess($entity, $operation, $account);
    if ($operation !== 'delete' || !$this->entityType->hasHandlerClass('drubricks_screen')) {
      return $result;
    }
    $cacheability = (new CacheableMetadata())->addCacheableDependency($entity);
    $screen = $this->entityTypeManager->getHandler($this->entityTypeId, 'drubricks_screen');
    $reasons = $screen instanceof ScreenHandler ? $screen->deleteBlockers($entity, $cacheability) : [];
    if ($reasons) {
      return AccessResult::forbidden(implode(' ', array_map('strval', $reasons)))->addCacheableDependency($cacheability);
    }
    // Deletable now: the answer changes when the blocking records do.
    return $result instanceof RefinableCacheableDependencyInterface ? $result->addCacheableDependency($cacheability) : $result;
  }

  /**
   * The own / any / admin permissions of an operation.
   */
  protected function permissionAccess(EntityInterface $entity, string $operation, AccountInterface $account): AccessResultInterface {
    $admin = $this->entityType->getAdminPermission();
    if ($admin && $account->hasPermission($admin)) {
      return AccessResult::allowed()->cachePerPermissions();
    }
    $verb = self::OPERATIONS[$operation] ?? NULL;
    if ($verb === NULL) {
      return AccessResult::neutral();
    }
    $type = $this->entityTypeId;
    if ($account->hasPermission("$verb any $type")) {
      return AccessResult::allowed()->cachePerPermissions();
    }
    if ($entity instanceof EntityOwnerInterface && $account->hasPermission("$verb own $type")) {
      return AccessResult::allowedIf((int) $entity->getOwnerId() === (int) $account->id())
        ->cachePerPermissions()
        ->cachePerUser()
        ->addCacheableDependency($entity);
    }
    return AccessResult::neutral()->cachePerPermissions();
  }

  /**
   * {@inheritdoc}
   */
  protected function checkCreateAccess(AccountInterface $account, array $context, $entity_bundle = NULL): AccessResultInterface {
    $admin = $this->entityType->getAdminPermission();
    return AccessResult::allowedIfHasPermissions($account, array_filter([$admin, 'create ' . $this->entityTypeId]), 'OR');
  }

}
